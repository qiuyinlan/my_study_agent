/* ══════════════════ 八、总装 ══════════════════ */

/**
 * 组装 system prompt。
 *
 * 段落顺序按**变化频率**排：越稳定的越靠前。
 * DeepSeek 的上下文缓存按前缀匹配，前面一变，后面全部失效。
 * 所以这里有一条硬规矩：**任何每轮都会变的东西（尤其是时间）必须放在最后**。
 * 早先能力声明里嵌了当前时间，导致缓存从那一行往后全废 —— 见 capabilityBlock 的注释。
 *
 * 流程段落是**全量注入**的。曾经按意图正则匹配着注入，但实测 8 条常用说法漏 4 条
 * （"我想开始学线代了"匹配不到 start，"你都能干啥"匹配不到 help）。漏掉的后果是
 * 模型拿不到用户自己定的那套步骤，只能即兴发挥。而流程段落完全静态、缓存友好，
 * 全量注入的实际成本约 200 token 当量。
 */
export function assembleSystemPrompt({ profile, caps, blocks = {} }) {
  /* ── 稳定层：几乎永不变化（缓存的主力）── */
  const stable = [
    PERSONA_CORE,
    SAFETY_RULES,
    WORK_PRINCIPLES,
    flowSection(),
  ].filter(Boolean).join('\n\n---\n\n');

  /* ── 半稳定层：跟着设置和档案走 ── */
  const semi = [
    toneBlock(profile),
    capabilityBlock(caps),
    blocks.profile ? `# 用户档案\n\n${blocks.profile}` : '',
    blocks.memories ? `# 长期记忆（高重要性，常驻）\n\n${blocks.memories}` : '',
  ].filter(Boolean).join('\n\n---\n\n');

  /* ── 易变层：每轮都变，放最后，不能污染前面的缓存 ── */
  const volatile = [
    suspendBlock(profile),
    blocks.keyTasks ? `# 今日关键任务\n\n${blocks.keyTasks}` : '',
    blocks.board ? `# 任务状态\n\n${blocks.board}` : '',
    blocks.points ? `# 积分账本\n\n${blocks.points}` : '',
    blocks.today ? `# 当下的情况\n\n${blocks.today}` : '',
  ].filter(Boolean).join('\n\n---\n\n');

  return [stable, semi, volatile].filter(Boolean).join('\n\n═══════════════════\n\n');
}

export function promptStats(prompt) {
  let cjk = 0;
  for (const ch of prompt) if (/[\u4e00-\u9fff]/.test(ch)) cjk++;
  return {
    chars: prompt.length,
    tokens: Math.round(cjk * 0.75 + (prompt.length - cjk) * 0.3),
  };
}
