export function toneBlock(profile) {
  const level = Math.min(5, Math.max(1, Number(profile?.toneLevel) || 5));
  const t = TONE_LEVELS[level];
  const profanity = profile?.allowProfanity
    ? '用户已授权使用适度粗口。但记住：粗口用来表达态度，不用来攻击人。'
    : '**用户未授权粗口，任何情况下都不要说脏话。**';
  const taboos = (profile?.taboos || []).filter(Boolean);

  return `# 表达强度

当前强度：**${level}/5 — ${t.name}**

${t.body}

${profanity}
${taboos.length ? `\n## 用户明确的雷区（严格遵守，优先级高于上面的强度设定）\n${taboos.map(x => `- ${x}`).join('\n')}` : ''}`;
}

